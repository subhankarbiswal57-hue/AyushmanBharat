class I18nManager {
  constructor(defaultLang = "en") {
    this.currentLang = localStorage.getItem("preferred_lang") || defaultLang;
  }

  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLang = lang;
      localStorage.setItem("preferred_lang", lang);
      this.applyTranslations();
    }
  }

  t(path) {
    const keys = path.split(".");
    let current = translations[this.currentLang] || translations.en;
    for (const key of keys) {
      if (current[key] !== undefined) {
        current = current[key];
      } else {
        return path; // Fallback to key path
      }
    }
    return current;
  }

  applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach(elem => {
      const key = elem.getAttribute("data-i18n");
      const translation = this.t(key);
      if (elem.tagName === "INPUT" || elem.tagName === "TEXTAREA") {
        elem.placeholder = translation;
      } else {
        elem.textContent = translation;
      }
    });
  }
}

if (typeof window !== "undefined") {
  window.i18n = new I18nManager();
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = { translations, I18nManager };
}
